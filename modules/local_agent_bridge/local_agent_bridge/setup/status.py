import re
import shlex
import subprocess

from .planner import Operation, Plan

OPTIONAL_FEATURES = {
    "code_retrieval": "shared.code-retrieval.",
    "structural_retrieval": "shared.structural-retrieval.",
    "checkpoint_compaction": "shared.checkpoint-compaction.",
}


def _resource_status(op: Operation) -> str:
    if op.details.get("retire"):
        return "retiring"
    if op.before.get("kind") == "missing":
        return "missing"
    if op.conflict:
        return "conflict"
    if op.action == "unchanged":
        return "current"
    return "outdated"


def _resource_sources(op: Operation, resource_root: Path) -> list[str]:
    rid = op.resource_id
    if rid in {"shared.local-worker", "shared.local-reviewer"}:
        return [
            str((resource_root / "integrations/opencode-agent.example.json").resolve()),
            str((resource_root / "skills/local-agent-handoff/resources/local-worker.md").resolve()),
        ]
    if rid.endswith(".instructions.rendered"):
        return [
            str((resource_root / "profiles/AGENTS.md").resolve()),
            str((resource_root / "instructions/coordinator.snippet.md").resolve()),
        ]
    if rid in {"codex.instructions", "agy.instructions"} and op.source is not None:
        return [
            str(op.source.resolve()),
            str((resource_root / "profiles/AGENTS.md").resolve()),
            str((resource_root / "instructions/coordinator.snippet.md").resolve()),
        ]
    if op.source is not None:
        return [str(op.source.resolve())]
    if rid == "codex.config":
        return [str((resource_root / "profiles/codex.toml").resolve())]
    if rid == "agy.defaults":
        return [str((resource_root / "dotfiles_llms/gemini/settings.json").resolve())]
    if rid.startswith("shared.code-retrieval.") or rid.startswith("shared.structural-retrieval."):
        name = rid.rsplit(".", 1)[-1] + ".js"
        return [str((resource_root / "opencode-tools" / name).resolve())]
    if rid == "shared.checkpoint-compaction.plugin":
        return [str((resource_root / "opencode-plugins/local_agent_checkpoint.js").resolve())]
    # Other managed config contributions are generated by the setup code from
    # package resources and the user's current config; identify that generator.
    return [
        str((resource_root.parent / "setup/planner.py").resolve()),
        str((resource_root.parent / "setup/manifest.py").resolve()),
        str((resource_root.parent / "setup/profiles.py").resolve()),
    ]


def _tree_diff(op: Operation) -> dict:
    """Describe missing/extra/changed entries in an inspectable copied tree."""
    if op.kind != "tree" or op.source is None or op.before.get("kind") == "missing":
        return {"missing": [], "extra": [], "changed": []}
    if op.before.get("kind") == "link":
        # Valid links already expose the source tree; never traverse a mismatched target.
        return {"missing": [], "extra": [], "changed": []}

    def entries(root: Path) -> dict[str, str]:
        result = {}
        for item in sorted(root.rglob("*")):
            relative = item.relative_to(root).as_posix()
            result[relative] = (
                hashlib.sha256(item.read_bytes()).hexdigest()
                if item.is_file()
                else "directory"
            )
        return result

    try:
        source = entries(op.source)
        installed = entries(op.path)
    except OSError:
        return {"missing": [], "extra": [], "changed": [], "error": "tree_read_failed"}
    return {
        "missing": sorted(source.keys() - installed.keys()),
        "extra": sorted(installed.keys() - source.keys()),
        "changed": sorted(
            key for key in source.keys() & installed.keys()
            if source[key] != installed[key]
        ),
    }


def _version_tuple(value: str) -> tuple[int, ...] | None:
    if not re.fullmatch(r"\d+(?:\.\d+)*", value):
        return None
    return tuple(int(part) for part in value.split("."))


def _source_repository(module_path: Path, package_version: str) -> dict:
    """Associate the active module with Git only when that file is tracked."""
    try:
        result = subprocess.run(
            ["git", "-C", str(module_path.parent), "rev-parse", "--show-toplevel"],
            capture_output=True, text=True, check=False, timeout=2,
        )
    except (OSError, subprocess.TimeoutExpired):
        return {"state": "unavailable", "path": None, "revision": None,
                "worktree_clean": None, "package_version": None,
                "newer_than_active_package": None}
    if result.returncode != 0:
        return {"state": "not_associated", "path": None, "revision": None,
                "worktree_clean": None, "package_version": None,
                "newer_than_active_package": None}
    root = Path(result.stdout.strip()).resolve()
    try:
        relative = module_path.resolve().relative_to(root).as_posix()
    except ValueError:
        relative = ""
    if not relative:
        return {"state": "not_associated", "path": None, "revision": None,
                "worktree_clean": None, "package_version": None,
                "newer_than_active_package": None}
    try:
        tracked = subprocess.run(
            ["git", "-C", str(root), "ls-files", "--error-unmatch", "--", relative],
            capture_output=True, text=True, check=False, timeout=2,
        )
    except (OSError, subprocess.TimeoutExpired):
        return {"state": "unavailable", "path": None, "revision": None,
                "worktree_clean": None, "package_version": None,
                "newer_than_active_package": None}
    if tracked.returncode != 0:
        return {"state": "not_associated", "path": None, "revision": None,
                "worktree_clean": None, "package_version": None,
                "newer_than_active_package": None}
    try:
        head = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, check=False, timeout=2,
        )
        revision = head.stdout.strip() if head.returncode == 0 else None
    except (OSError, subprocess.TimeoutExpired):
        revision = None
    project_file = module_path.parent.parent / "pyproject.toml"
    project_relative = project_file.relative_to(root).as_posix() if project_file.is_relative_to(root) else None
    try:
        package_relative = module_path.parent.relative_to(root).as_posix()
        status_args = ["git", "-C", str(root), "status", "--porcelain", "--", package_relative]
        if project_relative:
            status_args.append(project_relative)
        dirty = subprocess.run(
            status_args, capture_output=True, text=True, check=False, timeout=2
        )
        worktree_clean = dirty.returncode == 0 and not dirty.stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        worktree_clean = None
    source_version = None
    try:
        import tomllib

        source_version = tomllib.loads(project_file.read_text(encoding="utf-8"))["project"]["version"]
    except (OSError, KeyError, ValueError):
        pass
    active_tuple = _version_tuple(package_version)
    source_tuple = _version_tuple(source_version) if isinstance(source_version, str) else None
    newer = source_tuple > active_tuple if source_tuple and active_tuple else None
    return {
        "state": "associated",
        "path": str(root),
        "revision": revision,
        "worktree_clean": worktree_clean,
        "package_version": source_version,
        "newer_than_active_package": newer,
    }


def package_provenance(
    package_version: str,
    *,
    module_path: Path,
    resources_path: Path,
) -> dict:
    module_path = Path(module_path).resolve()
    resources_path = Path(resources_path).resolve()
    package_root = module_path.parent
    return {
        "package": {
            "name": "local-agent-bridge",
            "version": package_version,
            "module_path": str(module_path),
            "package_path": str(package_root),
            "resources_path": str(resources_path),
        },
        "source_repository": _source_repository(module_path, package_version),
    }


def build_status_report(
    plan: Plan,
    *,
    package_version: str,
    module_path: Path,
    resources_path: Path,
    repository: dict | None = None,
) -> dict:
    """Summarize plan operations without applying or otherwise mutating setup."""
    resources = []
    for op in plan.operations:
        status = _resource_status(op)
        kind = op.kind
        verification = "semantic" if kind in {"json", "toml", "block"} else "byte_exact"
        actual_hash = op.before.get("hash")
        expected_hash = op.desired_hash or op.summary().get("desired_hash")
        tree_diff = _tree_diff(op) if status != "current" else {
            "missing": [], "extra": [], "changed": []
        }
        resources.append({
            "resource_id": op.resource_id,
            "status": status,
            "path": str(op.path),
            "kind": kind,
            "installed_type": op.before.get("kind", "missing"),
            "installed_target": op.before.get("target"),
            "method": (op.method if kind in {"file", "tree"} else "managed-in-place"),
            "verification": verification,
            "byte_hash_matches": actual_hash == expected_hash if actual_hash is not None else False,
            "desired_hash": expected_hash,
            "tree_diff": tree_diff,
            "source_paths": _resource_sources(op, Path(resources_path)),
            "conflict": op.conflict,
            "retire": bool(op.details.get("retire")),
        })

    active = [item for item in resources if not item["retire"]]
    counts = {
        "total": len(active),
        "current": sum(item["status"] == "current" for item in active),
        "outdated": sum(item["status"] == "outdated" for item in active),
        "missing": sum(item["installed_type"] == "missing" for item in active),
        "conflicts": sum(bool(item["conflict"]) for item in active),
        "retiring": sum(item["retire"] for item in resources),
    }
    if counts["conflicts"]:
        state = "conflicts"
    elif counts["missing"] == counts["total"] and counts["total"]:
        state = "not_installed"
    elif counts["missing"] or counts["outdated"] or counts["retiring"]:
        state = "out_of_sync"
    else:
        state = "in_sync"
    summary = {"state": state, **counts}

    feature_values = {
        "code_retrieval": plan.code_retrieval,
        "structural_retrieval": plan.structural_retrieval,
        "checkpoint_compaction": plan.checkpoint_compaction,
    }
    features = {}
    for name, prefix in OPTIONAL_FEATURES.items():
        matching = [item for item in resources if item["resource_id"].startswith(prefix)]
        if name == "structural_retrieval":
            matching.extend(item for item in resources
                            if item["resource_id"].startswith("shared.code-retrieval.")
                            and item not in matching)
        if not feature_values[name]:
            installation_state = "not_applicable"
        elif any(item["conflict"] for item in matching):
            installation_state = "conflict"
        elif any(item["status"] in {"missing", "outdated"} for item in matching):
            installation_state = "out_of_sync"
        else:
            installation_state = "current"
        features[name] = {
            "enabled": bool(feature_values[name]),
            "status": "enabled" if feature_values[name] else "disabled",
            "installation_state": installation_state,
            "resources": [item["resource_id"] for item in matching],
        }

    provenance = package_provenance(
        package_version, module_path=module_path, resources_path=resources_path
    )
    if repository is not None:
        provenance["source_repository"] = repository
    provenance["resource_sources"] = {
        item["resource_id"]: item["source_paths"] for item in resources
    }
    return {
        "summary": summary,
        "features": features,
        "provenance": provenance,
        "resources": resources,
        "warnings": list(plan.warnings),
        "selection": {
            "home": str(plan.layout.home),
            "state_dir": str(plan.layout.state),
            "clients": list(plan.clients),
            "strategy": plan.strategy,
            "mode": plan.mode,
            "adopt": list(plan.adopt),
            "code_retrieval": plan.code_retrieval,
            "structural_retrieval": plan.structural_retrieval,
            "checkpoint_compaction": plan.checkpoint_compaction,
        },
    }


_COLORS = {
    "green": "\033[32m",
    "yellow": "\033[33m",
    "red": "\033[31m",
    "cyan": "\033[36m",
    "dim": "\033[2m",
    "reset": "\033[0m",
}


def format_status_report(report: dict, *, color: bool = False) -> str:
    summary = report["summary"]
    state = summary["state"]
    label = {
        "in_sync": ("IN SYNC", "green"),
        "out_of_sync": ("OUT OF SYNC", "yellow"),
        "not_installed": ("NOT INSTALLED", "red"),
        "conflicts": ("CONFLICTS", "red"),
    }.get(state, (state.upper().replace("_", " "), "yellow"))

    def paint(text: str, color_name: str) -> str:
        if not color:
            return text
        return _COLORS[color_name] + text + _COLORS["reset"]

    def quote_arg(value: str) -> str:
        if os.name == "nt":
            return "'" + value.replace("'", "''") + "'"
        return shlex.quote(value)

    def setup_command(action: str) -> str:
        selection = report["selection"]
        args = [
            "local-agent", "setup", action,
            "-H", quote_arg(selection["home"]),
            "-S", quote_arg(selection["state_dir"]),
            "-c", *selection["clients"],
            "-s", selection["strategy"],
            "-m", selection["mode"],
        ]
        if selection["adopt"]:
            args.extend(["-A", *selection["adopt"]])
        for name, enabled in (
            ("code-retrieval", selection["code_retrieval"]),
            ("structural-retrieval", selection["structural_retrieval"]),
            ("checkpoint-compaction", selection["checkpoint_compaction"]),
        ):
            args.append("--" + ("" if enabled else "no-") + name)
        return " ".join(args)

    lines = [f"Installation: {paint(label[0], label[1])}"]
    lines.append(
        "Current: {current}  Outdated: {outdated}  Missing: {missing}  "
        "Conflicts: {conflicts}".format(**summary)
    )
    package = report["provenance"]["package"]
    lines.append(f"Package: {package['name']} {package['version']}")
    lines.append(f"Loaded from: {package['module_path']}")
    lines.append(f"Resources from: {package['resources_path']}")
    repository = report["provenance"]["source_repository"]
    if repository["state"] == "associated":
        details = []
        if repository.get("revision"):
            details.append(f"revision {repository['revision']}")
        if repository.get("package_version"):
            details.append(f"package version {repository['package_version']}")
        if repository.get("worktree_clean") is False:
            details.append("package files modified")
        newer = repository.get("newer_than_active_package")
        if newer is True:
            details.append("source version is newer")
        suffix = f" ({'; '.join(details)})" if details else ""
        lines.append(f"Source repository: {repository['path']}{suffix}")
    elif repository["state"] == "not_associated":
        lines.append("Source repository: not associated with the active package")
    else:
        lines.append("Source repository: unable to inspect")

    lines.append("\nOptional features:")
    feature_labels = {
        "code_retrieval": "code retrieval",
        "structural_retrieval": "structural retrieval",
        "checkpoint_compaction": "checkpoint compaction",
    }
    for name, feature in report["features"].items():
        if feature["status"] == "disabled":
            feature_text = f"DISABLED  {feature_labels[name]} (optional; not installed)"
            feature_color = "dim"
        else:
            feature_text = f"ENABLED   {feature_labels[name]} ({feature['installation_state']})"
            feature_color = "green" if feature["installation_state"] == "current" else "yellow"
        lines.append(paint(feature_text, feature_color))

    lines.append("\nManaged resources:")
    statuses = {
        "current": ("CURRENT", "green"),
        "outdated": ("OUTDATED", "yellow"),
        "missing": ("MISSING", "red"),
        "conflict": ("CONFLICT", "red"),
        "retiring": ("RETIRING", "cyan"),
    }
    for item in report["resources"]:
        tag, tag_color = statuses.get(item["status"], (item["status"].upper(), "yellow"))
        method = item["method"]
        verification = item["verification"].replace("_", " ")
        line = f"{tag:9} {item['resource_id']} [{method}; {verification}] {item['path']}"
        lines.append(paint(line, tag_color))
        if item["installed_target"]:
            lines.append(f"  Installed link target: {item['installed_target']}")
        if item["conflict"]:
            lines.append(f"  Conflict: {item['conflict']}")
        diff = item.get("tree_diff", {})
        if diff.get("missing"):
            lines.append("  Missing files: " + ", ".join(diff["missing"]))
        if diff.get("changed"):
            lines.append("  Changed files: " + ", ".join(diff["changed"]))
        if diff.get("extra"):
            lines.append("  Extra files: " + ", ".join(diff["extra"]))
        for source in item["source_paths"]:
            lines.append(f"  Source: {source}")

    for warning in report.get("warnings", []):
        lines.append("\nNotice: " + warning)

    if state == "in_sync":
        lines.append("\nAction: No setup changes required.")
    elif summary["conflicts"]:
        lines.append("\nAction: Reconcile the listed conflicts, then rerun:")
        lines.append("        " + setup_command("plan"))
        lines.append("        " + setup_command("apply") + " (after the plan reports no conflicts)")
    else:
        lines.append("\nAction: " + setup_command("plan"))
        lines.append("        " + setup_command("apply"))
    return "\n".join(lines)
