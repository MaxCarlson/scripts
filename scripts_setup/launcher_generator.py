"""Authoritative generator for cross-platform unified wrappers and manifest."""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

if sys.version_info >= (3, 11):
    import tomllib
else:
    import tomli as tomllib  # type: ignore

GENERATOR_VERSION = "0.2.0"
MANAGED_SIGNATURE_WINDOWS = f"@REM Scripts Toolkit Managed Wrapper v{GENERATOR_VERSION}"
MANAGED_SIGNATURE_POSIX = f"# Scripts Toolkit Managed Wrapper v{GENERATOR_VERSION}"

# Marker substrings that identify legacy wrappers generated by older scripts
LEGACY_MARKERS_WINDOWS = (
    r'set "_V=%_B%..\.venv\Scripts"',
    r'set "_VENV_PY=',
    r'set "_PY_ABS=',
    r"Scripts Toolkit Managed Wrapper",
)
LEGACY_MARKERS_POSIX = (
    r'T="$DIR/../.venv/bin/',
    r'VENV_PY="$DIR/../.venv/bin/python"',
    r"Scripts Toolkit Managed Wrapper",
)


@dataclass(frozen=True)
class CommandEntry:
    name: str
    program_id: str
    kind: str  # "console_script", "python_file", "shell_script"
    source_path: str
    target: str
    target_windows: str
    target_posix: str
    version: str
    distribution: Optional[str] = None
    entry_point: Optional[str] = None

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        # Drop None keys for cleaner JSON
        return {k: v for k, v in data.items() if v is not None}


@dataclass
class CollisionReport:
    duplicate_names: Dict[str, List[str]] = field(default_factory=dict)
    case_insensitive_clashes: Dict[str, List[str]] = field(default_factory=dict)

    @property
    def has_collisions(self) -> bool:
        return bool(self.duplicate_names or self.case_insensitive_clashes)


@dataclass
class WrapperClassification:
    path: Path
    status: str  # "managed_current", "managed_legacy", "unmanaged"
    details: str = ""


@dataclass
class MigrationPlan:
    commands_to_generate: Dict[str, CommandEntry]
    collisions: CollisionReport
    managed_up_to_date: List[Path] = field(default_factory=list)
    managed_to_update: List[Path] = field(default_factory=list)
    missing_to_create: List[str] = field(default_factory=list)
    unmanaged_preserved: List[Path] = field(default_factory=list)
    obsolete_managed: List[Path] = field(default_factory=list)


@dataclass
class MigrationReport:
    is_dry_run: bool
    manifest_path: Path
    backup_path: Optional[Path]
    created_count: int
    updated_count: int
    unchanged_count: int
    preserved_unmanaged_count: int
    removed_obsolete_count: int
    collisions_detected: int
    details: List[str] = field(default_factory=list)


@dataclass
class RollbackReport:
    restored_count: int
    errors: List[str] = field(default_factory=list)


def _read_embedded_version(path: Path) -> str:
    """Extract embedded __version__ from standalone script."""
    try:
        content = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return "0.1.0"
    match = re.search(r'''(?m)^\s*__version__\s*=\s*["']([^"']+)["']''', content)
    return match.group(1).strip() if match else "0.1.0"


def scan_repository_programs(repo_root: Path) -> Dict[str, CommandEntry]:
    """Scan repo-owned modules, pyscripts, and shell scripts.
    
    Strictly discovers repository-owned programs and excludes arbitrary
    third-party packages in virtual environments.
    """
    root = repo_root.resolve()
    commands: Dict[str, CommandEntry] = {}

    # 1. Modules under modules/*/pyproject.toml
    modules_dir = root / "modules"
    if modules_dir.is_dir():
        for mod in sorted(modules_dir.iterdir()):
            pyproject = mod / "pyproject.toml"
            if not pyproject.is_file():
                continue
            try:
                with pyproject.open("rb") as f:
                    data = tomllib.load(f)
            except Exception:
                continue

            project = data.get("project", {})
            dist_name = project.get("name", mod.name)
            dist_version = project.get("version", "0.1.0")
            scripts = project.get("scripts", {})

            source_rel = str(mod.relative_to(root)).replace("\\", "/")
            for script_name, ep in scripts.items():
                commands[script_name] = CommandEntry(
                    name=script_name,
                    program_id=f"module:{dist_name}",
                    kind="console_script",
                    source_path=source_rel,
                    target=f".venv/Scripts/{script_name}.exe" if os.name == "nt" else f".venv/bin/{script_name}",
                    target_windows=f".venv/Scripts/{script_name}.exe",
                    target_posix=f".venv/bin/{script_name}",
                    version=dist_version,
                    distribution=dist_name,
                    entry_point=ep,
                )

    # 2. Modules under pscripts/modules/*/pyproject.toml if present
    pscripts_mod_dir = root / "pscripts" / "modules"
    if pscripts_mod_dir.is_dir():
        for mod in sorted(pscripts_mod_dir.iterdir()):
            pyproject = mod / "pyproject.toml"
            if not pyproject.is_file():
                continue
            try:
                with pyproject.open("rb") as f:
                    data = tomllib.load(f)
            except Exception:
                continue

            project = data.get("project", {})
            dist_name = project.get("name", mod.name)
            dist_version = project.get("version", "0.1.0")
            scripts = project.get("scripts", {})

            source_rel = str(mod.relative_to(root)).replace("\\", "/")
            for script_name, ep in scripts.items():
                commands[script_name] = CommandEntry(
                    name=script_name,
                    program_id=f"module:{dist_name}",
                    kind="console_script",
                    source_path=source_rel,
                    target=f".venv/Scripts/{script_name}.exe" if os.name == "nt" else f".venv/bin/{script_name}",
                    target_windows=f".venv/Scripts/{script_name}.exe",
                    target_posix=f".venv/bin/{script_name}",
                    version=dist_version,
                    distribution=dist_name,
                    entry_point=ep,
                )

    # 3. Standalone Python scripts under pyscripts/*.py
    pyscripts_dir = root / "pyscripts"
    if pyscripts_dir.is_dir():
        for script in sorted(pyscripts_dir.glob("*.py")):
            if script.name in ("__init__.py", "setup.py"):
                continue
            name = script.stem
            version = _read_embedded_version(script)
            rel_path = str(script.relative_to(root)).replace("\\", "/")
            commands[name] = CommandEntry(
                name=name,
                program_id=f"pyscript:{rel_path}",
                kind="python_file",
                source_path=rel_path,
                target=rel_path,
                target_windows=rel_path,
                target_posix=rel_path,
                version=version,
            )

    # 4. Standalone shell scripts under shell-scripts/*.sh
    shell_dir = root / "shell-scripts"
    if shell_dir.is_dir():
        for script in sorted(shell_dir.glob("*.sh")):
            name = script.stem
            rel_path = str(script.relative_to(root)).replace("\\", "/")
            commands[name] = CommandEntry(
                name=name,
                program_id=f"shell:{rel_path}",
                kind="shell_script",
                source_path=rel_path,
                target=rel_path,
                target_windows=rel_path,
                target_posix=rel_path,
                version="0.1.0",
            )

    return commands


def detect_collisions(commands: Dict[str, CommandEntry]) -> CollisionReport:
    """Analyze command dictionary for name collisions or Windows case-insensitivity conflicts."""
    report = CollisionReport()
    lower_map: Dict[str, List[str]] = {}

    for name in commands:
        low = name.lower()
        lower_map.setdefault(low, []).append(name)

    for low, names in lower_map.items():
        if len(names) > 1:
            report.case_insensitive_clashes[low] = sorted(names)

    return report


def classify_wrapper(path: Path) -> WrapperClassification:
    """Classify a wrapper file in bin/ as managed_current, managed_legacy, or unmanaged."""
    if not path.is_file() and not path.is_symlink():
        return WrapperClassification(path=path, status="unmanaged", details="Not a file")

    try:
        content = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return WrapperClassification(path=path, status="unmanaged", details="Unreadable file")

    # Current signature check
    if MANAGED_SIGNATURE_WINDOWS in content or MANAGED_SIGNATURE_POSIX in content:
        return WrapperClassification(path=path, status="managed_current", details="Current managed signature")

    # Legacy markers check
    is_windows = path.suffix.lower() == ".cmd"
    markers = LEGACY_MARKERS_WINDOWS if is_windows else LEGACY_MARKERS_POSIX
    for marker in markers:
        if marker in content:
            return WrapperClassification(
                path=path,
                status="managed_legacy",
                details=f"Legacy wrapper identified by marker: {marker[:30]}...",
            )

    return WrapperClassification(path=path, status="unmanaged", details="Custom or unmanaged user script")


def is_managed_wrapper(path: Path) -> bool:
    """Return True if the file was generated by current or legacy generator."""
    cls = classify_wrapper(path)
    return cls.status in ("managed_current", "managed_legacy")


def generate_windows_wrapper(command_name: str) -> str:
    """Generate portable, high-fidelity Windows .cmd wrapper."""
    return (
        f"{MANAGED_SIGNATURE_WINDOWS}\r\n"
        "@echo off\r\n"
        "setlocal\r\n"
        'set "_BIN=%~dp0"\r\n'
        'set "_ROOT=%_BIN%..\\"\r\n'
        'set "_VENV_PY=%_ROOT%.venv\\Scripts\\python.exe"\r\n'
        'set "_MANIFEST=%_ROOT%scripts_manifest.json"\r\n'
        'if not exist "%_VENV_PY%" (\r\n'
        '  echo [ERROR] Python venv interpreter not found at %_VENV_PY% 1>&2\r\n'
        "  exit /b 127\r\n"
        ")\r\n"
        '"%_VENV_PY%" -m script_logging.launcher --manifest "%_MANIFEST%" --command "%~n0" --wrapper "%~f0" -- %*\r\n'
        "exit /b %ERRORLEVEL%\r\n"
    )


def generate_posix_wrapper(command_name: str) -> str:
    """Generate portable, high-fidelity POSIX bash wrapper."""
    return f"""#!/usr/bin/env bash
{MANAGED_SIGNATURE_POSIX}
set -euo pipefail
DIR="$(cd -- "$(dirname -- "${{BASH_SOURCE[0]}}")" && pwd)"
ROOT="$(cd -- "$DIR/.." && pwd)"
VENV_PY="$ROOT/.venv/bin/python"
MANIFEST="$ROOT/scripts_manifest.json"
if [ ! -x "$VENV_PY" ]; then
  echo "[ERROR] Python venv interpreter not found at $VENV_PY" 1>&2
  exit 127
fi
exec "$VENV_PY" -m script_logging.launcher --manifest "$MANIFEST" --command "${{0##*/}}" --wrapper "$0" -- "$@"
"""


def write_wrapper(
    wrapper_path: Path,
    command_name: str,
    *,
    is_windows: Optional[bool] = None,
    overwrite_unmanaged: bool = False,
) -> bool:
    """Safely write a unified managed wrapper, refusing to overwrite unmanaged files."""
    if is_windows is None:
        is_windows = (wrapper_path.suffix.lower() == ".cmd") or (os.name == "nt")

    if wrapper_path.exists() or wrapper_path.is_symlink():
        if not overwrite_unmanaged and not is_managed_wrapper(wrapper_path):
            return False

    content = generate_windows_wrapper(command_name) if is_windows else generate_posix_wrapper(command_name)
    wrapper_path.parent.mkdir(parents=True, exist_ok=True)

    if wrapper_path.is_file() and not wrapper_path.is_symlink():
        try:
            existing = wrapper_path.read_text(encoding="utf-8")
            if existing == content:
                return False
        except OSError:
            pass

    newline = "\r\n" if is_windows else "\n"
    wrapper_path.write_text(content, encoding="utf-8", newline=newline)
    if not is_windows:
        try:
            wrapper_path.chmod(0o755)
        except OSError:
            pass
    return True


def generate_manifest(repo_root: Path, target_path: Optional[Path] = None) -> Path:
    """Scan repository programs and write atomic scripts_manifest.json."""
    root = repo_root.resolve()
    manifest_file = target_path or (root / "scripts_manifest.json")
    commands = scan_repository_programs(root)

    manifest_data = {
        "schema_version": 1,
        "repository_id": "MaxCarlson/scripts",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "generator_version": GENERATOR_VERSION,
        "commands": {cmd.name: cmd.to_dict() for cmd in sorted(commands.values(), key=lambda c: c.name)},
    }

    tmp_file = manifest_file.with_suffix(".tmp")
    tmp_file.write_text(json.dumps(manifest_data, indent=2), encoding="utf-8")
    tmp_file.replace(manifest_file)
    return manifest_file


def analyze_migration(repo_root: Path, bin_dir: Path) -> MigrationPlan:
    """Produce comprehensive migration plan without making any disk modifications."""
    commands = scan_repository_programs(repo_root)
    collisions = detect_collisions(commands)

    plan = MigrationPlan(commands_to_generate=commands, collisions=collisions)

    is_windows = os.name == "nt"

    if bin_dir.is_dir():
        existing_files = sorted(bin_dir.iterdir())
    else:
        existing_files = []

    # Map existing files by stem
    active_command_names = set(commands.keys())
    existing_by_stem: Dict[str, Path] = {}
    for f in existing_files:
        stem = f.stem if f.suffix.lower() == ".cmd" else f.name
        existing_by_stem[stem] = f

        classification = classify_wrapper(f)
        if classification.status == "managed_current":
            if stem in active_command_names:
                plan.managed_up_to_date.append(f)
            else:
                plan.obsolete_managed.append(f)
        elif classification.status == "managed_legacy":
            if stem in active_command_names:
                plan.managed_to_update.append(f)
            else:
                plan.obsolete_managed.append(f)
        else:
            plan.unmanaged_preserved.append(f)

    # Check for commands missing wrappers
    for cmd_name in commands:
        expected_wrapper_name = f"{cmd_name}.cmd" if is_windows else cmd_name
        wrapper_path = bin_dir / expected_wrapper_name
        if not wrapper_path.exists():
            plan.missing_to_create.append(cmd_name)

    return plan


def migrate_wrappers(
    repo_root: Path,
    bin_dir: Path,
    *,
    dry_run: bool = True,
    backup_dir: Optional[Path] = None,
    cleanup: bool = False,
) -> MigrationReport:
    """Generate or update wrappers and manifest with backup and rollback support.
    
    Guarantees:
    - Never mutates disk in dry-run mode.
    - Preserves unmanaged user wrappers untouched.
    - Backs up existing managed files before replacing when apply is specified.
    """
    root = repo_root.resolve()
    bin_path = bin_dir.resolve()
    plan = analyze_migration(root, bin_path)

    report = MigrationReport(
        is_dry_run=dry_run,
        manifest_path=root / "scripts_manifest.json",
        backup_path=None,
        created_count=len(plan.missing_to_create),
        updated_count=len(plan.managed_to_update),
        unchanged_count=len(plan.managed_up_to_date),
        preserved_unmanaged_count=len(plan.unmanaged_preserved),
        removed_obsolete_count=len(plan.obsolete_managed) if cleanup else 0,
        collisions_detected=len(plan.collisions.case_insensitive_clashes),
    )

    if dry_run:
        report.details.append(f"[DRY-RUN] Discovered {len(plan.commands_to_generate)} repo commands.")
        existing_count = len(list(bin_path.iterdir())) if bin_path.is_dir() else 0
        report.details.append(f"[DRY-RUN] Existing wrappers in bin/: {existing_count}")
        report.details.append(f"[DRY-RUN] Up-to-date managed wrappers: {len(plan.managed_up_to_date)}")
        report.details.append(f"[DRY-RUN] Legacy managed wrappers to update: {len(plan.managed_to_update)}")
        report.details.append(f"[DRY-RUN] Missing wrappers to create: {len(plan.missing_to_create)}")
        report.details.append(f"[DRY-RUN] Unmanaged / custom wrappers preserved: {len(plan.unmanaged_preserved)}")
        report.details.append(f"[DRY-RUN] Obsolete managed wrappers: {len(plan.obsolete_managed)}")
        return report

    # --- APPLY MODE ---
    bin_path.mkdir(parents=True, exist_ok=True)

    # 1. Create backup if there are existing files to update/remove
    if backup_dir is None:
        timestamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
        backup_path = bin_path.parent / f".launcher_backup_{timestamp}"
    else:
        backup_path = backup_dir.resolve()

    backup_path.mkdir(parents=True, exist_ok=True)
    report.backup_path = backup_path

    # Back up existing files in bin (preserving existing baseline files if already backed up)
    for f in bin_path.iterdir():
        if f.is_file():
            dest = backup_path / f.name
            if not dest.exists():
                shutil.copy2(f, dest)

    # 2. Write manifest
    generate_manifest(root)

    # 3. Create or update wrappers
    is_windows = os.name == "nt"
    for cmd_name in plan.commands_to_generate:
        wrapper_name = f"{cmd_name}.cmd" if is_windows else cmd_name
        wrapper_path = bin_path / wrapper_name

        # If file exists and is unmanaged: DO NOT TOUCH
        if wrapper_path.exists() and not is_managed_wrapper(wrapper_path):
            continue

        content = generate_windows_wrapper(cmd_name) if is_windows else generate_posix_wrapper(cmd_name)
        wrapper_path.write_text(content, encoding="utf-8")
        if not is_windows:
            try:
                wrapper_path.chmod(0o755)
            except OSError:
                pass

    # 4. Cleanup obsolete if requested
    if cleanup:
        for obsolete in plan.obsolete_managed:
            if is_managed_wrapper(obsolete):
                try:
                    obsolete.unlink()
                except OSError:
                    pass

    return report


def rollback_wrappers(backup_dir: Path, bin_dir: Path) -> RollbackReport:
    """Restore bin/ wrappers from an existing backup directory."""
    backup_path = backup_dir.resolve()
    bin_path = bin_dir.resolve()
    report = RollbackReport(restored_count=0)

    if not backup_path.is_dir():
        report.errors.append(f"Backup directory does not exist: {backup_path}")
        return report

    bin_path.mkdir(parents=True, exist_ok=True)
    for f in backup_path.iterdir():
        if f.is_file():
            try:
                shutil.copy2(f, bin_path / f.name)
                report.restored_count += 1
            except OSError as exc:
                report.errors.append(f"Failed to restore {f.name}: {exc}")

    return report


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Cross-platform wrapper generator and migration tool for scripts toolkit.",
    )
    parser.add_argument("-n", "--dry-run", action="store_true", default=True, help="Analyze and report without writing (default)")
    parser.add_argument("-a", "--apply", action="store_true", help="Apply migration and write wrappers and manifest")
    parser.add_argument("-w", "--write", action="store_true", help="Alias for --apply")
    parser.add_argument("-b", "--backup-dir", type=Path, default=None, help="Directory to store pre-migration backups")
    parser.add_argument("-r", "--rollback", type=Path, default=None, help="Roll back bin/ wrappers from specified backup directory")
    parser.add_argument("-c", "--cleanup", action="store_true", help="Remove obsolete managed wrappers (with confirmation in apply mode)")
    parser.add_argument("-V", "--version", action="version", version=f"%(prog)s {GENERATOR_VERSION}")
    parser.add_argument("-v", "--verbose", action="store_true", help="Detailed report output")
    parser.add_argument("--repo-root", type=Path, default=None, help="Path to repository root")
    parser.add_argument("--bin-dir", type=Path, default=None, help="Path to bin directory")

    args = parser.parse_args(argv)

    repo_root = (args.repo_root or Path(__file__).resolve().parents[1]).resolve()
    bin_dir = (args.bin_dir or repo_root / "bin").resolve()

    # Rollback mode
    if args.rollback:
        report = rollback_wrappers(args.rollback, bin_dir)
        if report.errors:
            print("[ERROR] Rollback encountered errors:\n" + "\n".join(report.errors), file=sys.stderr)
            return 1
        print(f"[SUCCESS] Rollback complete: restored {report.restored_count} files to {bin_dir}")
        return 0

    apply_mode = args.apply or args.write
    is_dry_run = not apply_mode

    report = migrate_wrappers(
        repo_root=repo_root,
        bin_dir=bin_dir,
        dry_run=is_dry_run,
        backup_dir=args.backup_dir,
        cleanup=args.cleanup,
    )

    mode_label = "DRY-RUN (No files modified)" if is_dry_run else "APPLIED MIGRATION"
    print("\n=======================================================")
    print(f" Scripts Toolkit Wrapper Migration Report: {mode_label}")
    print("=======================================================")
    print(f"Repository Root:      {repo_root}")
    print(f"Bin Directory:        {bin_dir}")
    print(f"Manifest Path:        {report.manifest_path}")
    if report.backup_path:
        print(f"Backup Directory:     {report.backup_path}")
    print("-------------------------------------------------------")
    print(f"Missing (To Create):  {report.created_count}")
    print(f"Legacy (To Update):   {report.updated_count}")
    print(f"Up-to-Date Managed:   {report.unchanged_count}")
    print(f"Preserved Unmanaged:  {report.preserved_unmanaged_count}")
    print(f"Obsolete Managed:     {report.removed_obsolete_count}")
    print(f"Collisions Detected:  {report.collisions_detected}")
    print("=======================================================\n")

    if args.verbose or is_dry_run:
        for detail in report.details:
            print(detail)

    return 0


if __name__ == "__main__":
    sys.exit(main())
